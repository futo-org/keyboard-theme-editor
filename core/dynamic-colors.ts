export function flattenDynamicColors(theme: Theme, assetStore: IAssetStore) {
    for(const [k, v] of Object.entries(theme.colors)) {
        if(v in DynamicColorMap) {
            (theme.colors as any)[k] = (DynamicColorMap as any)[v];
        }
    }

    for(const v of Object.values(assetStore.store)) {
        if(v.meta.kind === "background") {
            const data = v.data as BackgroundAsset;

            if(data.colorKind === "themed" && data.backgroundToken in DynamicColorMap && data.foregroundToken in DynamicColorMap) {
                data.colorKind = "constant";
                data.backgroundConstant = (DynamicColorMap as any)[data.backgroundToken];
                data.foregroundConstant = (DynamicColorMap as any)[data.foregroundToken];
            }
        }
    }

    console.log(theme.colors);

    console.log(assetStore.store);
}